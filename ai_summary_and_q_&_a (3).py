import whisper
import re
from transformers import AutoTokenizer
from transformers import pipeline
from google.colab import drive
from google.colab import files
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_community.vectorstores import FAISS
from langchain_core.prompts import PromptTemplate
import glob
import json
import faiss
import numpy as np

drive.mount('/content/drive')

audios = glob.glob('/content/drive/MyDrive/Audio files/*')
print(len(audios))

model = whisper.load_model("base")

texts = []

for audio in audios:
    result = model.transcribe(audio,  fp16=False)
    texts.append(result["text"])

text = " ".join(texts)
print(len(text))

print(len(text))

words_to_remove = ["-", "TEDx", "Talks", "(128K)", "(1)", ".mp3", "TEDxVancouver", "TEDxVancouver"]
pattern = r'\b(?:' + '|'.join(words_to_remove) + r')\b'

text = re.sub(pattern, '', text, flags=re.IGNORECASE)

text = re.sub(r'\(.*?\)|\[.*?\]|\{.*?\}', '', text)

text = re.sub(r'\b\d+(\.\d+)?\b', '', text)

print(len(text))

print(text)

tokenizer = AutoTokenizer.from_pretrained("gpt2")

tokens = tokenizer(text)
print(tokens)

input_ids = tokens["input_ids"]
print(input_ids)

splitter = RecursiveCharacterTextSplitter(
    chunk_size=500,
    chunk_overlap=50
)

chunks = splitter.split_text(text)

embedding_model = HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2"
)

embedded = embedding_model.embed_documents(chunks)
print(len(embedded))

print(len(chunks))

"""Let's check the FAISS"""

vectorstore = FAISS.from_texts(
    chunks,
    embedding_model
)

"""Let's use Pretrained LLM"""

generator = pipeline(
    "text-generation",
    model="TinyLlama/TinyLlama-1.1B-Chat-v1.0",
    device_map="auto"
)

# Save Vector Store
vectorstore.save_local("faiss_index")

with open("chunks.json", "w") as f:
    json.dump(chunks, f)

with open("transcripts.json", "w") as f:
    json.dump(texts, f)

